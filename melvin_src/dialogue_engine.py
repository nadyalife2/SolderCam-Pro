def get_recent_dialog_context(db_path: str, limit: int = 4) -> list:
    """Извлекает последние N реплик диалога для ChatML контекста."""
    try:
        conn = sqlite3.connect(db_path)
        cur = conn.cursor()
        cur.execute("SELECT role, content FROM memory_log ORDER BY id DESC LIMIT ?", (limit,))
        rows = cur.fetchall()
        conn.close()
        # Разворачиваем в хронологический порядок
        return rows[::-1]
    except Exception:
        return []


