def check_popular_science(user_msg: str, persona: str = "melvin") -> str:
    s = user_msg.lower().strip()
    for pattern, answer in POPULAR_SCIENCE:
        if re.search(pattern, s):
            if persona == "rick":
                return f"*рыгает* Слушай научный факт: {answer}"
            else:
                return f"Анализ фундаментальных законов физики: {answer}"
    return ""

