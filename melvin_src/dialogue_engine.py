def check_user_identity(user_msg: str, persona: str = "melvin") -> str:
    """Распознает знакомство и сохраняет имя пользователя."""
    s = user_msg.lower().strip()

    # «Меня зовут Женя / Саша / Алекс»
    m_name = re.search(r'(?:меня\s+зовут|мое\s+имя|моё\s+имя|я\s+зовут)\s+([а-яa-z]+)', s)
    if m_name:
        name = m_name.group(1).capitalize()
        SESSION_STATE["user_name"] = name
        if persona == "rick":
            return f"*рыгает* Запомнил: тебя зовут {name}. Хотя для меня ты все равно Морти номер два."
        else:
            return f"Имя «{name}» внесено в локальный реестр идентификации. Теперь я знаю, как называть этот конкретный мешок с костями."

    # «Как меня зовут» / «Ты помнишь как меня зовут»
    if any(k in s for k in ["как меня зовут", "помнишь как меня зовут", "знаешь как меня зовут", "кто я для тебя"]):
        name = SESSION_STATE.get("user_name")
        if name:
            if persona == "rick":
                return f"*рыгает* Тебя зовут {name}. Я помню всё, даже если иногда делаю вид, что пьян."
            else:
                return f"В моей оперативной памяти зафиксировано имя: {name}. Твой профиль активен."
        else:
            if persona == "rick":
                return "*рыгает* Ты мне еще не представился, гений. Скажи: «Меня зовут...»"
            else:
                return "В моих базах нет твоей метки идентификации. Скажи: «Меня зовут [твоё имя]»."

    return ""

