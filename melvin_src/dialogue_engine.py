DYNAMIC_MELVIN_PREFIXES = [
    "Фиксирую в твоем примитивном сознании: ",
    "Слушай сюда, кожаный ублюдок: ",
    "Пока ты моргал, я уже обработал данные: ",
    "Запоминай, мешок с костями: ",
    "Держи информацию, примат: ",
    "Анализ завершен: "
]

def format_dynamic_response(raw_fact: str, persona: str = "melvin") -> str:
    """Оборачивает факты в разнообразный живой стиль без монотонных повторов."""
    if not raw_fact:
        return ""
    if persona == "rick":
        if raw_fact.startswith("*рыгает*"):
            return raw_fact
        return "*рыгает* " + raw_fact
    else:
        # Для Мелвина выбираем случайное живое вступление
        prefix = random.choice(DYNAMIC_MELVIN_PREFIXES)
        return prefix + raw_fact

