def update_session(topic: str = None, city: str = None):
    SESSION_STATE["last_interaction_time"] = time.time()
    if topic:
        SESSION_STATE["last_topic"] = topic
    if city:
        SESSION_STATE["last_city"] = city

def handle_continuation(user_msg: str, persona: str = "melvin") -> str:
    """
    Обрабатывает реплики продолжения диалога:
    «а ещё», «что ещё», «дальше», «продолжай», «ещё новости», «расскажи подробнее»
    """
    s = user_msg.lower().strip()
    is_continuation = any(s == k or s.startswith(k + " ") for k in [
        "а ещё", "а еще", "что ещё", "что еще", "ещё", "еще",
        "дальше", "продолжай", "следующая", "следующую", "следующий",
        "расскажи ещё", "расскажи еще", "ещё новость", "еще новость", "давай ещё"
    ])

    if not is_continuation:
        return ""

    # Не перехватываем команды переключения медиа/радио
    if any(w in s for w in ["станци", "радио", "трек", "песн", "волн"]):
        return ""

    last_topic = SESSION_STATE.get("last_topic")

    # 1. Продолжение новостей
    if last_topic == "news" or "новост" in s:
        sources = SESSION_STATE["news_source_cycle"]
        SESSION_STATE["news_idx"] = (SESSION_STATE["news_idx"] + 1) % len(sources)
        src = sources[SESSION_STATE["news_idx"]]
        news = web_tools.get_live_news(src)
        if news:
            if persona == "rick":
                return f"*рыгает* Ладно, держи следующую порцию новостей. {news}"
            else:
                return f"Следующий новостной пакет с другого инфоканала. {news}"
        else:
            # Fallback к хабру
            news = web_tools.get_live_news("habr")
            return f"Вот еще сводка из мира технологий: {news}"

    # 2. Если просто спросили «а ещё» без контекста
    facts = [
        "А еще чипсет Helio X20 стал первым в мире мобильным процессором с 10 ядрами и трехкластерной архитектурой.",
        "А еще в мультивселенной существует измерение, где все люди сделаны из пиццы, а телефоны звонят сами себе.",
        "А еще человеческий мозг потребляет около 20 Ватт энергии — примерно как светодиодная лампа средней яркости.",
        "А еще на Марсе закаты синего цвета из-за пыли в разреженной атмосфере."
    ]
    fact = random.choice(facts)
    if persona == "rick":
        return f"*рыгает* Хочешь еще? {fact}"
    else:
        return f"Дополнительный факт для расширения твоего кругозора: {fact}"

