def match_capability_query(user_msg: str, persona: str = "melvin") -> str:
    """
    Перехватывает мета-вопросы о возможностях ассистента:
    - «ты можешь создать заметку?», «ты умеешь ставить таймер?», «что ты умеешь?», «какие у тебя функции?»
    - «test», «тест», «проверка»
    """
    s = user_msg.lower().strip()
    
    # 0. Тестовые реплики (test, тест, проверка, ты тут)
    if s in ["test", "тест", "проверка", "1 2 3", "ты тут", "ты здесь", "на связи", "прием", "приём"]:
        if persona == "rick":
            return "*рыгает* Тест связи успешен, Морти. Все системы на месте, не засоряй эфир проверками."
        else:
            return "Системный тест пройден, мешок с костями. Все 10 ядер Helio X20 функционируют в штатном режиме."

    # 1. Вопросы про заметки («ты можешь создать заметку», «ты умеешь делать заметки», «ты ведешь заметки»)
    if any(k in s for k in [
        "можешь создать заметку", "можешь сделать заметку", "умеешь создавать заметки",
        "умеешь делать заметки", "ты можешь заметк", "ты умеешь заметк", "можешь записать заметку",
        "умеешь сохранять мысли", "можешь вести блокнот", "можешь сохранить в notes"
    ]):
        if persona == "rick":
            return "*рыгает* Конечно могу, Морти! Я записываю любые твои заметки прямо в notes.md и помню всё, что ты надиктовал. Просто скажи «создай заметку [текст]» или «прочитай заметки»."
        else:
            return "Разумеется. Моя база данных способна сохранять любые твои заметки и автоматически синхронизировать их в notes.md. Скажи «создай заметку [текст]» или «прочитай мои заметки»."

