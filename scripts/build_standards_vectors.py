def tokenize(text: str) -> list:
    """Токенизация текста с лемматизацией и n-граммами."""
    text = text.lower()
    tokens = re.findall(r'[a-zа-яё0-9_\-\.]+', text)
    clean = []
    stopwords = {"и", "в", "на", "с", "по", "для", "не", "от", "до", "при", "из", "или", "что", "как", "так", "то"}
    for t in tokens:
        t = t.strip(".-_")
        if len(t) >= 2 and t not in stopwords:
            clean.append(t)
    return clean

